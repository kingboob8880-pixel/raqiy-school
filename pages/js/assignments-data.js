/** Сколько дней идёт задание — вытаскиваем из duration, а не заводим ещё
 *  одно поле: два поля об одном и том же разъезжаются, и тогда карточка
 *  говорит «10 дней», а сетка рисует семь клеток. */
function daysOf(duration) {
  const m = /^(\d+)\s*дн/.exec(String(duration || ""));
  return m ? Number(m[1]) : 0;
}

// Раскладываем по записям один раз при загрузке модуля.
for (const items of Object.values(ASSIGNMENTS)) {
  for (const a of items) {
    a.steps = STEPS[a.id] || [];
    a.days = daysOf(a.duration);
    if (COUNTERS[a.id]) a.counter = COUNTERS[a.id];
    if (INTENTS[a.id]) a.intent = INTENTS[a.id];
  }
}

/** Все задания одним списком, с номером модуля у каждого — для страницы
 *  «Практика», где они показываются вперемешку и фильтруются. */
export function allAssignments() {
  const out = [];
  for (const [mid, items] of Object.entries(ASSIGNMENTS)) {
    for (const a of items) out.push({ ...a, moduleId: Number(mid) });
  }
  return out;
}

/** Задания, привязанные к конкретной книге — для страницы книги.
 *  Пустой массив, если заданий нет: вызывающий код тогда просто не рисует
 *  блок, а не показывает пустую рамку. */
export function assignmentsForBook(docPath) {
  const out = [];
  for (const items of Object.values(ASSIGNMENTS)) {
    for (const a of items) if (a.book === docPath) out.push(a);
  }
  return out;
}

/** Номер модуля, которому принадлежит задание. Нужен странице книги:
 *  отметка о выполнении пишется в progress.{moduleId}, а сама страница
 *  книги о номере модуля ничего не знает. */
export function moduleOfAssignment(id) {
  for (const [mid, items] of Object.entries(ASSIGNMENTS)) {
    if (items.some((a) => a.id === id)) return Number(mid);
  }
  return null;
}
