/** Чего не хватает, чтобы случай можно было отправить. Пустой массив —
 *  можно. Проверка одна на сайт и на бота, чтобы правила приёма не
 *  различались в зависимости от того, откуда человек подаёт. */
export function missingFields(fields) {
  const out = [];
  for (const f of CASE_FIELDS) {
    const v = String(fields?.[f.key] || "").trim();
    if (v.length < f.min) out.push(f);
  }
  return out;
}

/** Готов ли ученик к допуску: принято нужное число случаев. */
export function supervisionPassed(student) {
  return (student?.supervision?.accepted || 0) >= CASES_REQUIRED;
}

