// Get formula by ID
export function getFormula(id: string): Formula | undefined {
  return FORMULAS.find(f => f.id === id);
}

// Get formulas by tag
export function getFormulasByTag(tag: string): Formula[] {
  return FORMULAS.filter(f => f.tags.includes(tag));
}

// Get formulas by organ
export function getFormulasByOrgan(organ: string): Formula[] {
  return FORMULAS.filter(f => f.organ === organ || f.organ === 'all');
}

// Search formulas
export function searchFormulas(query: string): Formula[] {
  const lowerQuery = query.toLowerCase();
  return FORMULAS.filter(f => 
    f.name.toLowerCase().includes(lowerQuery) ||
    f.transliteration.toLowerCase().includes(lowerQuery) ||
    f.translation.toLowerCase().includes(lowerQuery) ||
    f.tags.some(t => t.toLowerCase().includes(lowerQuery))
  );
}
